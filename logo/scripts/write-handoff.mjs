#!/usr/bin/env node
/**
 * Write <logo-dir>/handoff.yaml — the contract other skills read.
 *
 * Why this file exists: skill `branding` used to reach into mark-brief.md and
 * into the agent's memory to build the logo section. That is not a contract,
 * it is a coupling: neither skill could be installed without the other, and
 * nothing declared what `branding` was allowed to depend on.
 *
 * handoff.yaml is the whole interface. A consumer reads it and nothing deeper.
 *
 * Usage:
 *   node write-handoff.mjs <logo-dir> --recommended=logo-v1-x.svg \
 *     --referent="The first band of light above the horizon." \
 *     --alt=logo-v7-y.svg::route text::why it lost \
 *     --alt=logo-v8-z.svg::route text::why it lost \
 *     --lockup=aurora::Aurora::logo-lockup.svg::logo-lockup-light.svg
 *
 * --lockup entries list one wordmark pair per candidate brand name, so a
 * consumer can let the reader switch names. The MARK never changes with the
 * name — only the lockup does.
 *
 * With no --alt flags, every logo-v*.svg other than the recommended one is
 * listed with an empty reason and the script exits 1 — a set with unexplained
 * alternatives is filler, and the skill says so.
 */
import fs from 'node:fs'
import path from 'node:path'

const argv = process.argv.slice(2)
const dir = argv.find((a) => !a.startsWith('--'))
const opt = (k) => {
  const hit = argv.find((a) => a.startsWith('--' + k + '='))
  return hit ? hit.slice(k.length + 3) : undefined
}

if (!dir || !fs.existsSync(dir)) {
  console.error('usage: write-handoff.mjs <logo-dir> --recommended=<file> --referent="…" [--alt=file::route::why]')
  process.exit(2)
}

const marks = fs.readdirSync(dir).filter((f) => /^logo-v\d.*\.svg$/.test(f)).sort()
if (!marks.length) {
  console.error('no logo-v*.svg in ' + dir)
  process.exit(2)
}

const recommended = opt('recommended') || marks[0]
if (!marks.includes(recommended)) {
  console.error('recommended not found in dir: ' + recommended)
  process.exit(2)
}

const referent = opt('referent') || ''

const given = new Map(
  argv
    .filter((a) => a.startsWith('--alt='))
    .map((a) => a.slice(6).split('::'))
    .filter((p) => p.length >= 1)
    .map(([file, route = '', why = '']) => [file, { route, why }])
)

const alternatives = marks
  .filter((f) => f !== recommended)
  .map((file) => ({ file, ...(given.get(file) || { route: '', why: '' }) }))

const q = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"'

// One wordmark pair per candidate brand name. Missing files are reported, not
// silently listed: a consumer that switches to a name with no lockup shows the
// wrong brand on the page.
const lockups = argv
  .filter((a) => a.startsWith('--lockup='))
  .map((a) => a.slice(9).split('::'))
  .filter((p) => p.length === 4)
  .map(([slug, name, dark, light]) => ({ slug, name, dark, light }))

const missingLockups = lockups.filter(
  (l) => !fs.existsSync(path.join(dir, l.dark)) || !fs.existsSync(path.join(dir, l.light))
)

const yaml = [
  '# Generated by write-handoff.mjs — the contract consuming skills read.',
  '# Everything here is about the marks. Process provenance lives in strategy.yaml.',
  'recommended: ' + recommended,
  'referent: ' + q(referent),
  'alternatives:',
  ...alternatives.flatMap((a) => [
    '  - file: ' + a.file,
    '    route: ' + q(a.route),
    '    why_not: ' + q(a.why),
  ]),
  ...(lockups.length
    ? [
        '# The mark survives a rename; the wordmark does not. Switching names swaps',
        '# only these pairs — every logo-v*.svg and the favicon stay as they are.',
        'lockups:',
        ...lockups.flatMap((l) => [
          '  ' + l.slug + ':',
          '    name: ' + q(l.name),
          '    dark: ' + l.dark,
          '    light: ' + l.light,
        ]),
      ]
    : []),
  '',
].join('\n')

const out = path.join(dir, 'handoff.yaml')
fs.writeFileSync(out, yaml, 'utf8')

const missing = alternatives.filter((a) => !a.route.trim() || !a.why.trim())
console.log('wrote ' + out + ' (' + (alternatives.length + 1) + ' marks)')

if (!referent.trim()) {
  console.error('FAIL: no --referent. The recommended mark must say which exemplar, seen from where.')
}
if (missing.length) {
  console.error(
    'FAIL: ' + missing.length + ' alternative(s) with no route or no reason: ' +
      missing.map((a) => a.file).join(', ')
  )
  console.error('An alternative with no reason is filler. Fill them in and run again.')
}
if (missingLockups.length) {
  console.error(
    'FAIL: ' + missingLockups.length + ' lockup pair(s) not on disk: ' +
      missingLockups.map((l) => l.slug).join(', ')
  )
  console.error('Run make-lockup.mjs for each candidate name before writing the handoff.')
}
if (missing.length || missingLockups.length || !referent.trim()) process.exit(1)
